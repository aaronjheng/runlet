    static func completions(for prefix: String) -> [String] {
        let upper = prefix.uppercased()
        return commands.filter { $0.hasPrefix(upper) }.sorted { $0.localizedStandardCompare($1) == .orderedAscending }
    }

    /// Case-insensitive syntax lookup, e.g. `signature(for: "zadd")`.
    /// Returns nil for commands with no known signature.
    static func signature(for command: String) -> String? {
        signatures[command.uppercased()]
    }
